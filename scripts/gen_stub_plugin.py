#!/usr/bin/env python3
"""gen_stub_plugin.py — 生成 corpus_stubs 插件清单（可链接、不可执行）。

为什么需要这一层：语料里 219 个 (library, function) 还没有真实实现。缺绑定时
运行期报 RBINDING_MISSING，和「实现有 bug」混在一个失败类里，既不能加载也不能
逐条核实。这里把它们注册成 **stub**：import 能解析、符号能列出、调用时以
`not-implemented` 显式失败，并把归因表里的 class/evidence 原样带出来。

不变量：
  - 清单只覆盖**当前没有实现**的语料符号；已有实现的符号若出现在这里，
    pluginhost 的「一个符号只能有一个实现」判据会判红。
  - 每个符号的 loss = 归因表里的 `<class>: <evidence>`，非空、可机器解析。
  - 生成物可复现：`--check` 逐字节比对，漂移即 rc=1；读不到语料/表 rc=3。

用法：
  python3 scripts/gen_stub_plugin.py            # 写 plugins/corpus_stubs/
  python3 scripts/gen_stub_plugin.py --check    # 漂移判红（0 稳定 / 1 漂移 / 3 判不了）
"""
from __future__ import annotations

import argparse
import json
import os
import sys

try:
    import yaml
except Exception as e:  # pragma: no cover
    print(f"[gen-stub-plugin] 判不了：PyYAML 不可用（{e}）", file=sys.stderr)
    sys.exit(3)

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import library_coverage as lc  # noqa: E402
import unbound_attribution as ua  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT_DIR = os.path.join(ROOT, "plugins", "corpus_stubs")
MANIFEST = os.path.join(OUT_DIR, "ncoda-plugin.yaml")
SYMBOLS = os.path.join(OUT_DIR, "stub_symbols.json")

MANIFEST_HEADER = (
    "# GENERATED by scripts/gen_stub_plugin.py — do not edit by hand.\n"
    "# 语料调用面里尚未实现的符号：能链接、能加载，调用时显式 not-implemented。\n"
    "# 归因来源：docs/UNBOUND-ATTRIBUTION.md；实现一个就从本清单移除。\n"
)


def collect(corpus: str | None = None, table_path: str = ua.TABLE) -> dict[str, dict[str, dict]]:
    """返回 {library: {function: {class, evidence}}}：语料调用、但**没有真实现**的符号。

    「没有真实现」= 没有被 localtools/插件以 real|partial 绑定。stub 自身不算实现，
    所以本清单对同一语料是幂等的（重跑不会把自己删掉）；某个符号一旦被真实现
    插件接走，就会从这里消失——这正是「实现一个、降一个 stub」的闭环。
    """
    table = ua.load_table(table_path)
    ua.validate_overrides(table, lc.load_headers(lc.HEADERS))
    try:
        cov = lc.analyze(corpus or lc.DEFAULT_CORPUS)
    except lc.CannotJudge as e:
        raise ua.CannotJudge(str(e))

    realized: dict[str, set[str]] = {}
    for source in (lc.load_bindings(), lc.load_plugins()):
        for (lib, fn), meta in source.items():
            if lc.fidelity(meta) in ("real", "partial"):
                realized.setdefault(lib, set()).add(fn)

    out: dict[str, dict[str, dict]] = {}
    for lib, st in sorted(cov["libraries"].items()):
        missing = sorted(set(st["called"]) - realized.get(lib, set()))
        if not missing:
            continue
        row = table.get(lib)
        if not row:
            raise ua.CannotJudge(
                f"{lib}: corpus calls {missing} but the attribution table has no row")
        overrides = row.get("symbols") or {}
        for fn in missing:
            sym = overrides.get(fn)
            cls = sym["class"] if sym else row["class"]
            ev = sym["evidence"] if sym else row["evidence"]
            out.setdefault(lib, {})[fn] = {"class": cls, "evidence": ev}
    return out


def render(symbols: dict[str, dict[str, dict]]) -> tuple[str, str]:
    doc = {
        "schema": "ncoda.plugin/v1",
        "id": "corpus-stubs",
        "version": "0.1.0",
        "protocol": "ncoda-plugin/1",
        "type": "stdio",
        "command": ["python3", "server.py"],
        "timeout_ms": 30000,
        "libraries": [],
    }
    flat = {}
    for lib, fns in symbols.items():
        entry = {"library": lib, "fidelity": "stub", "functions": []}
        for fn, meta in fns.items():
            loss = f"{meta['class']}: {meta['evidence']}"
            entry["functions"].append({"name": fn, "fidelity": "stub", "loss": loss})
            flat[f"{lib}.{fn}"] = {"class": meta["class"], "evidence": meta["evidence"], "loss": loss}
        doc["libraries"].append(entry)
    manifest = MANIFEST_HEADER + yaml.safe_dump(
        doc, sort_keys=False, allow_unicode=True, default_flow_style=False, width=200)
    table = {
        "schema": "ncoda.corpus-stubs/v1",
        "source": "docs/UNBOUND-ATTRIBUTION.md",
        "symbols": dict(sorted(flat.items())),
    }
    return manifest, json.dumps(table, ensure_ascii=False, indent=1, sort_keys=False) + "\n"


def read(path: str) -> str:
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError as e:
        raise ua.CannotJudge(f"not readable: {path} ({e})")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default=os.environ.get("NCODA_CORPUS", lc.DEFAULT_CORPUS))
    ap.add_argument("--table", default=ua.TABLE)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    try:
        symbols = collect(args.corpus, args.table)
        manifest, table = render(symbols)
    except (ua.BadTable, ua.CannotJudge) as e:
        print(f"[gen-stub-plugin] 判不了：{e}", file=sys.stderr)
        return 3

    if args.check:
        problems = []
        for path, want in ((MANIFEST, manifest), (SYMBOLS, table)):
            got = read(path)
            if got != want:
                problems.append(path)
        if problems:
            for p in problems:
                print(f"[gen-stub-plugin] ✗ 与生成结果不一致：{os.path.relpath(p, ROOT)}"
                      "（运行 scripts/gen_stub_plugin.py 重新生成）", file=sys.stderr)
            return 1
        print(f"[gen-stub-plugin] ✓ 清单与语料调用面一致"
              f"（{len(symbols)} libraries · {sum(len(v) for v in symbols.values())} stub symbols）")
        return 0

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        fh.write(manifest)
    with open(SYMBOLS, "w", encoding="utf-8") as fh:
        fh.write(table)
    print(f"[gen-stub-plugin] 写入 {os.path.relpath(MANIFEST, ROOT)} / "
          f"{os.path.relpath(SYMBOLS, ROOT)}（{sum(len(v) for v in symbols.values())} symbols）")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
