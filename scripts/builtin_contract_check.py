#!/usr/bin/env python3
"""builtin_contract_check.py — open-core builtin result contracts (declaration source).

Declaration source (single authority): examples/builtins/<target>.yaml
Generated artifact (DO NOT EDIT):     pkg/builtin/contracts_language_gen.go

Why declaration, not inference: the open core declares the **language-level**
result port vocabulary (the fields of HTTPResponse and friends). Platform
adapters declare their own physical ports in the commercial repository and
inject them via pkg/builtin.RegisterContracts; the two sides are joined by the
language field name, not guessed from wire shapes.

The platform target tables used to be declared here; they moved to the commercial
repo with the adapter (ASSET-BOUNDARY P2c). The open target is now the
language itself (`ncoda-language`), so the open build no longer names a
platform.

Exit codes: 0 ok · 1 violation · 2 usage · 3 cannot judge (source/artifact read).
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

try:
    import yaml
except Exception as exc:  # pragma: no cover
    print(f"[builtin-contract] 判不了：PyYAML 不可用（{exc}）", file=sys.stderr)
    sys.exit(3)

SRC_DIR_REL = "examples/builtins"
OUT_REL = "pkg/builtin/contracts_language_gen.go"
REQUIRED_TARGETS = ("ncoda-language",)
MIN_PAIRS = 1  # non-vacuity floor: emptying the declaration must not go green

HEADER = """// Code generated by scripts/builtin_contract_check.py --write; DO NOT EDIT.
//
// 声明源 = examples/builtins/<target>.yaml（唯一权威，含 ② 证据口径）。
// 门禁校验「重新生成 == 本文件」；手工修改会在下一次门禁运行时报红。
//
// 本文件 = **语言层**（ncoda-language）。平台 target 的契约在商业仓经
// pkg/builtin.RegisterContracts 注入；开放模块从不链接闭源代码。
//
// 契约回答一个问题：**某个内建节点在某个目标平台上，语言层字段与平台物理口
// 如何对应**。两侧名字可以不同（语言 status_code ⇄ coze-biz statusCode），
// 所以 lowering（语言字段 → 平台口）与 raising（平台口 → 语言字段）必须共读
// 这一份数据；分成两份必然漂移（实测：同一事实曾散落 10 余处，且反向方向
// 一份都没有 ⇒ 往返断裂）。

package builtin

// contractsLanguage 是语言层的内建节点结果契约。
var contractsLanguage = map[string]map[string]NodeContract{
"""


def find_root(explicit: str | None) -> str | None:
    if explicit:
        return explicit if os.path.isdir(explicit) else None
    d = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return d if os.path.isfile(os.path.join(d, "go.mod")) else None


def go_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_all(root: str) -> dict[str, dict]:
    files = sorted(glob.glob(os.path.join(root, SRC_DIR_REL, "*.yaml")))
    if not files:
        raise FileNotFoundError(f"未找到声明文件：{SRC_DIR_REL}/*.yaml")
    out: dict[str, dict] = {}
    for path in files:
        with open(path, encoding="utf-8") as fh:
            doc = yaml.safe_load(fh)
        if not isinstance(doc, dict) or doc.get("schema_version") != 1:
            raise ValueError(f"{path}: schema_version 必须为 1")
        if not doc.get("target"):
            raise ValueError(f"{path}: 缺 target")
        for name in [doc["target"]] + list(doc.get("aliases") or []):
            if name in out:
                raise ValueError(f"目标 {name} 被多个声明文件覆盖")
            out[name] = doc
    missing = [t for t in REQUIRED_TARGETS if t not in out]
    if missing:
        raise ValueError(f"已知目标缺声明：{', '.join(missing)}（内建节点契约只能声明，不能推断）")
    return out


def render(targets: dict[str, dict]) -> str:
    lines = [HEADER]
    for target in sorted(targets):
        nodes = targets[target].get("builtins") or {}
        lines.append(f"\t{go_str(target)}: {{")
        for node in sorted(nodes):
            spec = nodes[node] or {}
            ports = spec.get("ports") or []
            if not ports:
                raise ValueError(f"{target}/{node}: ports 为空")
            lines.append(f"\t\t{go_str(node)}: {{Result: {go_str(spec.get('result', ''))}, Ports: []Port{{")
            for port in ports:
                for key in ("port", "lang", "type"):
                    if not port.get(key):
                        raise ValueError(f"{target}/{node}: 端口条目缺 {key}")
                lines.append(
                    f"\t\t\t{{Port: {go_str(port['port'])}, Lang: {go_str(port['lang'])}, "
                    f"Type: {go_str(port['type'])}}},"
                )
            lines.append("\t\t}},")
        lines.append("\t},")
    lines.append("}\n")
    lines.append("func init() { registerContracts(contractsLanguage) }\n")
    return "\n".join(lines)


def count_pairs(targets: dict[str, dict]) -> int:
    return sum(len((d.get("builtins") or {})) for d in targets.values())


def main() -> int:
    ap = argparse.ArgumentParser()
    group = ap.add_mutually_exclusive_group(required=False)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=None)
    args = ap.parse_args()
    if not args.write and not args.check:
        args.check = True

    root = find_root(args.root)
    if root is None:
        print("[builtin-contract] 判不了：找不到项目根（go.mod）", file=sys.stderr)
        return 3
    if not os.path.isdir(os.path.join(root, SRC_DIR_REL)):
        print(f"[builtin-contract] 判不了：声明源目录读不到：{SRC_DIR_REL}", file=sys.stderr)
        return 3
    try:
        targets = load_all(root)
        want = render(targets)
    except FileNotFoundError as exc:
        print(f"[builtin-contract] 判不了：{exc}", file=sys.stderr)
        return 3
    except ValueError as exc:
        print(f"✗ 声明源非法：{exc}", file=sys.stderr)
        return 1

    if count_pairs(targets) < MIN_PAIRS:
        print(f"✗ 非空转下界：生成 (target,node) 对 {count_pairs(targets)} < {MIN_PAIRS}", file=sys.stderr)
        return 1

    path = os.path.join(root, OUT_REL)
    if args.write:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(want)
        print(f"✓ 已写入 {OUT_REL}（{count_pairs(targets)} 个 (target,node) 对）")
        return 0

    try:
        with open(path, encoding="utf-8") as fh:
            current = fh.read()
    except OSError as exc:
        print(f"✗ 生成物读不到：{OUT_REL}（{exc}）—— 跑 --write", file=sys.stderr)
        return 1
    if current != want:
        print(f"✗ {OUT_REL} 与声明源不一致 —— 改声明源后没重新生成 / 生成物被手改；跑 --write",
              file=sys.stderr)
        return 1
    print(f"✓ 内建契约与声明源一致（{OUT_REL} · {count_pairs(targets)} 个 (target,node) 对）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
